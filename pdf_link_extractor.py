import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin
import argparse
import os
import re


def sanitize_filename_from_url(url: str) -> str:
    """Sanitizes a URL to create a safe filename."""
    # --- CHANGE: Ensure this logic is identical to other scripts ---
    filename_base = re.sub(r"https?://", "", url)
    filename_base = re.sub(r"[^a-zA-Z0-9_.-]", "_", filename_base).strip("_.-")
    return filename_base[:100]
    # --- END CHANGE ---


def extract_pdf_links(input_links_file: str, original_url_for_naming: str):
    base_url = "https://eparlib.nic.in"

    page_urls = []
    try:
        with open(input_links_file, "r", encoding="utf-8") as f:
            page_urls = [line.strip() for line in f.readlines() if line.strip()]
        if not page_urls:
            print(
                f"Warning: No URLs found in the input file: {input_links_file}. Exiting."
            )
            return
    except FileNotFoundError:
        print(
            f"Error: Input file '{input_links_file}' not found. Please ensure the previous script ran successfully."
        )
        return
    except Exception as e:
        print(f"Error reading input file {input_links_file}: {e}")
        return

    pdf_urls = []
    header = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/114.0.0.0 Safari/537.36",
        "Accept-Language": "en-US,en;q=0.9",
        "Referer": "https://eparlib.nic.in",
    }

    print(f"Processing {len(page_urls)} page URLs from {input_links_file}...")

    for i, page_url in enumerate(page_urls):
        print(f"[{i + 1}/{len(page_urls)}] Fetching page: {page_url}")
        try:
            resp = requests.get(page_url, headers=header, verify=False, timeout=10)
            resp.raise_for_status()
        except requests.exceptions.RequestException as e:
            print(f"Failed to load page {page_url}: {e}")
            continue
        except Exception as e:
            print(f"An unexpected error occurred while fetching {page_url}: {e}")
            continue

        soup = BeautifulSoup(resp.text, "html.parser")
        pdf_tag = soup.find(
            "a", href=lambda x: x and "bitstream" in x and x.lower().endswith(".pdf")
        )

        if pdf_tag:
            pdf_link = urljoin(base_url, pdf_tag["href"])
            pdf_urls.append(pdf_link)
            print(f"  PDF Found: {pdf_link}")
        else:
            print(f"  PDF not found on page: {page_url}")

    sanitized_url_name = sanitize_filename_from_url(original_url_for_naming)
    output_filename = f"pdf_links_for_{sanitized_url_name}.txt"

    # --- YOUR FIX (This part is correct) ---
    output_dir = os.path.join("link_extractor_scripts", "extracted_pdf_urls")
    os.makedirs(output_dir, exist_ok=True)
    full_output_path = os.path.join(output_dir, output_filename)
    # --- FIX ENDS HERE ---

    if pdf_urls:
        with open(full_output_path, "w", encoding="utf-8") as f:
            for link in pdf_urls:
                f.write(link + "\n")
        print(f"\nSuccessfully extracted {len(pdf_urls)} PDF links.")
        print(f"All PDF links saved to: {full_output_path}")
    else:
        print("\nNo PDF links were found and saved.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Extract PDF links from a list of page URLs generated by the previous script."
    )
    parser.add_argument(
        "input_url_for_naming",
        type=str,
        help="The original URL used by the previous script. Used to find the input file and name the output file.",
    )
    args = parser.parse_args()

    # --- CHANGE: Construct the input filename using the consistent sanitization logic ---
    # This now correctly finds the file created by `pdf_page_link_extractor_v2.py`.
    sanitized_input_url_name = sanitize_filename_from_url(args.input_url_for_naming)
    input_links_file_name = os.path.join(
        "link_extractor_scripts", "extracted_links", f"{sanitized_input_url_name}.txt"
    )
    # --- END CHANGE ---

    extract_pdf_links(input_links_file_name, args.input_url_for_naming)
